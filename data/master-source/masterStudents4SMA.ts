// Helper to generate realistic subject grades for each student in Kelas 4 / 1 SMA
function generateSubjectScores4SMA(seed: number): Record<string, number> {
  const scores: Record<string, number> = {};
  for (let i = 1; i <= 28; i++) {
    const subId = `s${i}`;
    const variance = ((seed * 31 + i * 17) % 29);
    const base = 75 + ((seed * 7) % 15);
    const finalScore = Math.min(98, Math.max(68, base + (variance - 14)));
    scores[subId] = finalScore;
  }
  return scores;
}

