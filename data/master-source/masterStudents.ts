// Helper to generate realistic subject grades for each student
function generateSubjectScores(seed: number): Record<string, number> {
  const scores: Record<string, number> = {};
  for (let i = 1; i <= 28; i++) {
    const subId = `s${i}`;
    // Generate realistic grades between 60 and 95
    const variance = ((seed * 17 + i * 23) % 29);
    const base = 68 + ((seed * 7) % 15);
    const finalScore = Math.min(95, Math.max(55, base + (variance - 14)));
    scores[subId] = finalScore;
  }
  return scores;
}

