// Helper to generate realistic subject grades for each student in Kelas 3 Intensif / 3 SMA
function generateSubjectScores3Int(seed: number): Record<string, number> {
  const scores: Record<string, number> = {};
  for (let i = 1; i <= 28; i++) {
    const subId = `s${i}`;
    const variance = ((seed * 29 + i * 19) % 27);
    const base = 76 + ((seed * 5) % 15);
    const finalScore = Math.min(99, Math.max(70, base + (variance - 13)));
    scores[subId] = finalScore;
  }
  return scores;
}

