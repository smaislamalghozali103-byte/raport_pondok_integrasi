// Helper to generate realistic subject grades for each student in Kelas 6 / 3 SMA
function generateSubjectScores6SMA(seed: number): Record<string, number> {
  const scores: Record<string, number> = {};
  for (let i = 1; i <= 28; i++) {
    const subId = `s${i}`;
    const variance = ((seed * 37 + i * 19) % 25);
    const base = 78 + ((seed * 5) % 15);
    const finalScore = Math.min(99, Math.max(72, base + (variance - 12)));
    scores[subId] = finalScore;
  }
  return scores;
}

