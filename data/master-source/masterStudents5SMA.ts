// Helper to generate realistic subject grades for each student in Kelas 5 / 2 SMA
function generateSubjectScores5SMA(seed: number): Record<string, number> {
  const scores: Record<string, number> = {};
  for (let i = 1; i <= 28; i++) {
    const subId = `s${i}`;
    const variance = ((seed * 31 + i * 17) % 27);
    const base = 77 + ((seed * 7) % 15);
    const finalScore = Math.min(99, Math.max(70, base + (variance - 13)));
    scores[subId] = finalScore;
  }
  return scores;
}

